"""Run against order-edit-ui-server.mjs + Vite, never against production."""
import json
import os
from pathlib import Path
from urllib.parse import urlparse
from playwright.sync_api import sync_playwright, expect

BASE = os.environ.get('UI_BASE_URL', 'http://127.0.0.1:5173')
assert urlparse(BASE).hostname in ('localhost', '127.0.0.1')
ARTIFACTS = Path('test-results/order-workspace')
ARTIFACTS.mkdir(parents=True, exist_ok=True)

with sync_playwright() as p:
    browser = p.chromium.launch(headless=True)
    page = browser.new_page(viewport={'width': 1440, 'height': 1000})
    errors = []
    page.on('pageerror', lambda error: errors.append(str(error)))
    page.request.post('http://127.0.0.1:3001/_fixture/reset')
    page.goto(f'{BASE}/?app=1&tenant=andina&view=approvals')
    local_login = page.get_by_role('button', name='Usar acceso local de desarrollo')
    local_login.click()
    page.get_by_role('button', name='Pedidos y pendientes', exact=True).click()
    page.get_by_role('button', name='Ver pedido y conversación', exact=True).first.click()
    dialog = page.get_by_role('dialog', name='Cliente de prueba')
    expect(dialog).to_be_visible()
    expect(dialog.get_by_text('Coca-Cola original', exact=True)).to_be_visible()
    expect(dialog.get_by_text('Veci, mejor dos gaseosas y cambia el Chocoramo por una leche Colanta. Pago por Bre-B.')).to_be_visible()
    page.screenshot(path=str(ARTIFACTS / 'desktop-order-chat.png'), full_page=True)
    dialog.get_by_role('button', name='Editar pedido', exact=True).click()
    dialog.get_by_label('Cantidad de Coca-Cola original').fill('2')
    dialog.get_by_role('button', name='Quitar Ponqué Chocoramo').click()
    dialog.get_by_label('Agregar producto').fill('leche')
    dialog.get_by_role('button', name='Leche entera Colanta').click()
    dialog.get_by_label('Medio de pago', exact=True).select_option('bre_b')
    dialog.get_by_label('Dirección', exact=True).fill('Calle 101 # 21-31, Bogotá')
    expect(dialog.locator('.ow-grand-total')).to_contain_text('22.200')
    expect(dialog.get_by_role('button', name='Guardar cambios')).to_be_disabled()
    dialog.get_by_label('Acordé con el cliente', exact=False).check()
    # Polling chat while editing must not replace the local order changes.
    page.request.post('http://127.0.0.1:3001/_fixture/message')
    expect(dialog.get_by_text('Gracias, aquí te espero.')).to_be_visible(timeout=12000)
    expect(dialog.get_by_label('Cantidad de Coca-Cola original')).to_have_value('2')
    page.screenshot(path=str(ARTIFACTS / 'desktop-edit.png'), full_page=True)
    dialog.get_by_role('button', name='Guardar cambios').click()
    expect(dialog.get_by_text('Cambios guardados. El pedido conserva su etapa.')).to_be_visible()
    expect(dialog.get_by_text('Resumen actualizado en cola para WhatsApp.')).to_be_visible()
    expect(dialog.get_by_role('button', name='Marcar tomado')).to_be_visible()
    dialog.get_by_text('Historial de cambios (1)').click()
    expect(dialog.get_by_text('22.200', exact=False).first).to_be_visible()
    dialog.get_by_role('button', name='Marcar tomado').click()
    expect(dialog.get_by_role('button', name='Marcar en camino')).to_be_visible(timeout=20000)
    # Competing update: preserve local values and show a conflict, not success.
    dialog.get_by_role('button', name='Editar pedido', exact=True).click()
    dialog.get_by_label('Cantidad de Coca-Cola original').fill('3')
    dialog.get_by_label('Acordé con el cliente', exact=False).check()
    page.request.post('http://127.0.0.1:3001/_fixture/conflict')
    dialog.get_by_role('button', name='Guardar cambios').click()
    expect(dialog.get_by_role('alert')).to_contain_text('El pedido cambió')
    expect(dialog.get_by_label('Cantidad de Coca-Cola original')).to_have_value('3')
    dialog.get_by_role('button', name='Recargar pedido').click()
    dialog.get_by_role('button', name='Descartar cambios').click()
    expect(dialog.get_by_role('button', name='Editar pedido', exact=True)).to_be_visible()
    dialog.get_by_role('button', name='Marcar en camino').click()
    expect(dialog.get_by_text('Este pedido ya está cerrado para edición.', exact=False)).to_be_visible(timeout=20000)
    expect(dialog.get_by_role('button', name='Editar pedido', exact=True)).to_have_count(0)
    page.screenshot(path=str(ARTIFACTS / 'desktop-dispatched.png'), full_page=True)

    mobile = browser.new_page(viewport={'width': 390, 'height': 844}, is_mobile=True, has_touch=True)
    mobile.on('pageerror', lambda error: errors.append(str(error)))
    mobile.request.post('http://127.0.0.1:3001/_fixture/reset')
    mobile.goto(f'{BASE}/?app=1&tenant=andina&view=approvals')
    mobile.get_by_role('button', name='Usar acceso local de desarrollo').click()
    mobile.get_by_role('button', name='Pedidos y pendientes', exact=True).last.click()
    mobile.get_by_role('button', name='Ver pedido y conversación', exact=True).first.click()
    compact = mobile.get_by_role('dialog', name='Cliente de prueba')
    expect(compact).to_be_visible()
    mobile.screenshot(path=str(ARTIFACTS / 'mobile-order.png'))
    compact.get_by_role('button', name='Conversación', exact=True).click()
    expect(compact.get_by_text('Veci, mejor dos gaseosas', exact=False)).to_be_visible()
    mobile.screenshot(path=str(ARTIFACTS / 'mobile-chat.png'))
    compact.get_by_role('button', name='Pedido', exact=True).click()
    compact.get_by_role('button', name='Editar pedido', exact=True).click()
    compact.get_by_label('Cantidad de Coca-Cola original').fill('2')
    compact.get_by_role('button', name='Conversación', exact=True).click()
    compact.get_by_role('button', name='Pedido', exact=True).click()
    expect(compact.get_by_label('Cantidad de Coca-Cola original')).to_have_value('2')
    compact.get_by_role('button', name='Cerrar pedido', exact=True).click()
    expect(compact.get_by_role('button', name='Seguir editando')).to_be_visible()
    compact.get_by_role('button', name='Seguir editando').click()
    assert not compact.evaluate('(element) => element.scrollWidth > element.clientWidth')
    compact.get_by_role('button', name='Cancelar edición').click()
    compact.get_by_role('button', name='Cerrar pedido', exact=True).click()
    expect(compact).to_have_count(0)
    assert not errors, errors
    (ARTIFACTS / 'result.json').write_text(json.dumps({'status': 'passed', 'desktop': [1440, 1000], 'mobile': [390, 844], 'pageErrors': errors}, indent=2))
    print('PASS desktop/mobile order editor: save, chat refresh, totals, conflict, status flow, read-only, unsaved changes.')
    browser.close()
