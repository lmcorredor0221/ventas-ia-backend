import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createApp } from '../index.js';
import { colombiaCatalogTestSeed300 } from '../data/colombiaCatalogExpansion.js';

// Reproduces the successful production conversation without calling Meta,
// Google, DeepSeek or any external service. The local platform state is the
// only source of truth for the simulation.
const WA_ID = '573219450893';
const TENANT_ID = 'andina';
const requestedProducts = {
  coca: /coca|1\.5|litro y medio/i,
  chocoramo: /chocoramo|chocorramo/i,
};

const simulationRoot = fs.mkdtempSync(path.join(os.tmpdir(), 'ventas-ia-production-conversation-'));
const reportRoot = path.join(process.cwd(), 'test-results-production-conversation');
fs.mkdirSync(reportRoot, { recursive: true });

try {
  const exactCatalog = colombiaCatalogTestSeed300.filter((product) => (
    product.sku === 'BOG-BEB-044' || product.sku === 'COL-226'
  ));
  assert.equal(exactCatalog.length, 2, 'El fixture debe tener las dos referencias de producción.');
  assert.equal(exactCatalog.reduce((sum, product) => sum + product.price, 0), 8800);

  const fullCatalog = colombiaCatalogTestSeed300;
  const runs = [
    { name: 'exact-production-catalog', catalog: exactCatalog, contextualProductSelectionV2: true },
    { name: 'full-300-catalog', catalog: fullCatalog, contextualProductSelectionV2: true },
  ];

  const reports = [];
  for (const [index, fixture] of runs.entries()) {
    reports.push(await runFixture(fixture, index));
  }

  const report = {
    generatedAt: new Date().toISOString(),
    mode: 'local-only',
    externalServicesCalled: false,
    sourceConversation: {
      greeting: 'Buenos días para un domicilio',
      products: 'Una Coca-Cola litro y medio y un chocorramo',
      address: 'Dimonti 1',
      payment: 'Bre-B',
    },
    runs: reports,
  };
  const reportPath = path.join(reportRoot, `production-conversation-${Date.now()}.json`);
  fs.writeFileSync(reportPath, `${JSON.stringify(report, null, 2)}\n`);
  console.log(JSON.stringify({
    reportPath,
    runs: reports.map((run) => ({
      name: run.name,
      success: run.success,
      steps: run.steps.map((step) => ({
        turn: step.turn,
        input: step.input,
        elapsedMs: step.elapsedMs,
        summary: step.summary,
        intent: step.intent,
        reply: step.reply,
        buttons: step.buttons,
        basket: step.basket,
        offerPurpose: step.offerPurpose,
      })),
      metrics: run.metrics,
      assertions: run.assertions,
    })),
  }, null, 2));
} finally {
  fs.rmSync(simulationRoot, { recursive: true, force: true });
}

async function runFixture(fixture, fixtureIndex) {
  const { app, store, runtime } = createApp({
    dataFile: path.join(simulationRoot, `${fixture.name}.json`),
    authRequired: false,
    csrfRequired: false,
    allowLocalCatalogFallback: true,
    whatsappMode: 'mock',
    backgroundWorkersEnabled: false,
    contextualProductSelectionV2: fixture.contextualProductSelectionV2,
    llmRequestTimeoutMs: 8000,
  });
  const server = app.listen(0, '127.0.0.1');
  const steps = [];
  const assertions = [];
  let base = null;

  try {
    const port = await new Promise((resolve) => server.once('listening', () => resolve(server.address().port)));
    base = `http://127.0.0.1:${port}`;
    seedFixture(store, fixture.catalog);

    let turn = 0;
    let last = await sendText(base, 'Buenos días para un domicilio', 'greeting', ++turn);
    steps.push(summarizeStep(last));

    last = await sendText(base, 'Una Coca-Cola litro y medio y un chocorramo', 'products', ++turn);
    steps.push(summarizeStep(last));

    // Resolve any catalog-selection cards generated by the contextual resolver.
    for (let guard = 0; guard < 4; guard += 1) {
      const offer = latestOffer(store, 'catalog_selection');
      if (!offer) break;
      const option = chooseCatalogOption(offer);
      last = await sendInteractive(base, option, option.title, `catalog-selection-${guard}`, ++turn);
      steps.push(summarizeStep(last));
    }

    const cartOffer = latestOffer(store, 'cart_review');
    if (cartOffer) {
      const option = optionByTitle(cartOffer, /continuar pedido/i) ?? cartOffer.options[0];
      last = await sendInteractive(base, option, option.title, 'continue-cart', ++turn);
      steps.push(summarizeStep(last));
    }

    const paymentOffer = latestOffer(store, 'payment_method');
    assert.ok(paymentOffer, `${fixture.name}: debe ofrecer medios de pago`);
    const paymentOption = optionByTitle(paymentOffer, /bre[- ]?b/i) ?? paymentOffer.options[0];
    last = await sendInteractive(base, paymentOption, paymentOption.title, 'payment-breb', ++turn);
    steps.push(summarizeStep(last));

    const confirmationOffer = latestOffer(store, 'order_confirmation');
    assert.ok(confirmationOffer, `${fixture.name}: debe mostrar confirmación final`);
    const confirmOption = optionByTitle(confirmationOffer, /confirmar pedido/i) ?? confirmationOffer.options[0];
    last = await sendInteractive(base, confirmOption, confirmOption.title, 'confirm-order', ++turn);
    steps.push(summarizeStep(last));

    const conversation = store.getState().conversations.find((item) => item.tenantId === TENANT_ID && item.waId === WA_ID);
    const order = (store.getState().ordersByTenant?.[TENANT_ID] ?? []).find((item) => item.conversationId === conversation?.id);
    const draft = conversation?.orderDraft ?? null;
    const itemNames = (draft?.items ?? []).map((item) => item.product?.name ?? item.catalogQuery);
    const subtotal = Number(draft?.subtotal ?? order?.subtotal ?? 0);
    const replyTexts = (conversation?.messages ?? []).filter((message) => message.role === 'agent').map((message) => message.text);
    const outbound = (store.getState().events ?? []).filter((event) => event.tenantId === TENANT_ID && event.type === 'tool.call.completed');

    assertions.push(assertion('two_unique_items', new Set(itemNames).size === 2, itemNames));
    assertions.push(assertion('expected_coca', itemNames.some((name) => requestedProducts.coca.test(name ?? '')), itemNames));
    assertions.push(assertion('expected_chocoramo', itemNames.some((name) => requestedProducts.chocoramo.test(name ?? '')), itemNames));
    assertions.push(assertion('subtotal_8800', subtotal === 8800, subtotal));
    assertions.push(assertion('payment_breb', draft?.paymentMethod === 'breb' || order?.paymentMethod === 'breb', draft?.paymentMethod ?? order?.paymentMethod));
    assertions.push(assertion('address_dimonti', String(order?.deliveryAddress ?? draft?.deliveryAddress ?? '').includes('Dimonti 1'), order?.deliveryAddress ?? draft?.deliveryAddress));
    assertions.push(assertion('order_created', Boolean(order?.id || conversation?.orderId), order?.id ?? conversation?.orderId));
    assertions.push(assertion('confirmation_has_reference', replyTexts.some((text) => /Pedido confirmado y registrado|Referencia:/i.test(text)), replyTexts));

    return {
      name: fixture.name,
      success: assertions.every((item) => item.passed),
      steps,
      assertions,
      metrics: {
        conversationId: conversation?.id ?? null,
        orderId: order?.id ?? conversation?.orderId ?? null,
        itemNames,
        subtotal,
        orderStatus: order?.status ?? null,
        activeOffersAfterRun: Object.values(store.getState().interactionOffersById ?? {}).filter((offer) => offer.status === 'active').map((offer) => offer.purpose),
        toolCalls: outbound.length,
        events: (store.getState().events ?? []).filter((event) => event.tenantId === TENANT_ID).length,
        telemetry: await getJson(`${base}/api/ops/telemetry?tenantId=${TENANT_ID}`),
      },
    };
  } catch (error) {
    return {
      name: fixture.name,
      success: false,
      steps,
      assertions: [...assertions, { name: 'runtime', passed: false, actual: error.message }],
      metrics: { telemetry: base ? await getJson(`${base}/api/ops/telemetry?tenantId=${TENANT_ID}`).catch(() => null) : null },
    };
  } finally {
    runtime.stop();
    await new Promise((resolve) => server.close(resolve));
  }
}

function seedFixture(store, catalog) {
  store.mutate((state) => {
    const tenant = state.tenants.find((item) => item.id === TENANT_ID);
    tenant.config.orderPolicy.deliveryFee = 0;
    tenant.config.orderPolicy.deliveryMinimumSubtotal = 0;
    tenant.config.orderPolicy.paymentMethods = [
      { id: 'cash', label: 'Efectivo', enabled: true },
      { id: 'card', label: 'Tarjeta', enabled: true },
      { id: 'breb', label: 'Bre-B', enabled: true },
    ];
    state.productsByTenant[TENANT_ID] = structuredClone(catalog);
    state.customerProfilesByTenant[TENANT_ID] ??= {};
    state.customerProfilesByTenant[TENANT_ID][WA_ID] = {
      sheetRowId: `sheet-production-simulation-${WA_ID}`,
      driveFileId: `drv-production-simulation-${WA_ID}`,
      phone: WA_ID,
      name: 'Luis Corredor',
      defaultAddress: 'Dimonti 1',
      addresses: [{ label: 'casa', address: 'Dimonti 1' }],
      preferences: { channel: 'whatsapp', deliveryDefault: true },
      createdAt: new Date().toISOString(),
      updatedAt: new Date().toISOString(),
    };
  });
}

function latestOffer(store, purpose) {
  return Object.values(store.getState().interactionOffersById ?? {})
    .filter((offer) => offer.conversationId === currentConversationId(store) && offer.purpose === purpose && offer.status === 'active')
    .at(-1) ?? null;
}

function currentConversationId(store) {
  return store.getState().conversations.find((item) => item.tenantId === TENANT_ID && item.waId === WA_ID)?.id;
}

function chooseCatalogOption(offer) {
  return offer.options.find((option) => /1\.5|mini|35\s*g/i.test(option.title)) ?? offer.options[0];
}

function optionByTitle(offer, pattern) {
  return offer.options.find((option) => pattern.test(option.title));
}

async function sendText(base, text, suffix, turn) {
  return postJson(`${base}/api/agent/run`, {
    tenantId: TENANT_ID,
    waId: WA_ID,
    profileName: 'Luis Corredor',
    text,
    messageId: `production-simulation-${suffix}-${turn}`,
  });
}

async function sendInteractive(base, option, title, suffix, turn) {
  return postJson(`${base}/api/agent/run`, {
    tenantId: TENANT_ID,
    waId: WA_ID,
    profileName: 'Luis Corredor',
    text: title,
    messageType: 'interactive',
    interactive: { type: 'button_reply', optionId: option.id, title },
    messageId: `production-simulation-${suffix}-${turn}`,
  });
}

function summarizeStep(run) {
  const conversation = run.conversation;
  const latest = [...(conversation?.messages ?? [])].reverse().find((message) => message.role === 'agent');
  const activeOffer = Object.values(run.interactionOffers ?? {}).find((offer) => offer.status === 'active') ?? null;
  const draft = conversation?.orderDraft ?? null;
  return {
    turn: null,
    input: null,
    elapsedMs: run.result?.telemetry?.durationMs ?? null,
    summary: run.result?.summary ?? null,
    intent: run.result?.plan?.intent ?? null,
    reply: latest?.text ?? null,
    buttons: latest?.interactive?.buttons?.map((button) => button.title) ?? activeOffer?.options?.map((option) => option.title) ?? [],
    basket: {
      items: (draft?.items ?? []).map((item) => ({ name: item.product?.name ?? item.catalogQuery, quantity: item.quantity, price: item.product?.price ?? null, lineTotal: item.lineTotal ?? null })),
      subtotal: draft?.subtotal ?? null,
      paymentMethod: draft?.paymentMethod ?? null,
      address: draft?.deliveryAddress ?? null,
    },
    raw: {
      executionMode: run.result?.plan?.executionMode ?? null,
      selectionStatuses: (draft?.items ?? []).map((item) => item.selectionStatus ?? null),
      activeOfferPurpose: activeOffer?.purpose ?? null,
    },
  };
}

function assertion(name, passed, actual) {
  return { name, passed, actual };
}

async function postJson(url, body) {
  const started = performance.now();
  const response = await fetch(url, {
    method: 'POST',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify(body),
  });
  const text = await response.text();
  assert.equal(response.ok, true, `${url} returned ${response.status}: ${text}`);
  const result = text ? JSON.parse(text) : {};
  result.result ??= {};
  result.result.telemetry = { durationMs: Number((performance.now() - started).toFixed(2)) };
  result.__elapsedMs = result.result.telemetry.durationMs;
  return result;
}

async function getJson(url) {
  const response = await fetch(url);
  const text = await response.text();
  assert.equal(response.ok, true, `${url} returned ${response.status}: ${text}`);
  return text ? JSON.parse(text) : {};
}
