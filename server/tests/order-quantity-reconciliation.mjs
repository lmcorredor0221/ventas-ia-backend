import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createAppAsync } from '../index.js';

// A customer may state a quantity before choosing the exact catalog variant.
// The later selection must replace the pending line, not reset its quantity to
// the interpreter fallback default of one.
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'via-order-quantity-reconciliation-'));
const { store, runtime, integrationOutbox } = await createAppAsync({
  storageDriver: 'json',
  whatsappMode: 'mock',
  contextualProductSelectionV2: false,
  backgroundWorkersEnabled: false,
  dataFile: path.join(dir, 'store.json'),
});

const tenantId = 'andina';
const conversationId = 'quantity-reconciliation';
const waId = '573000000901';
const cola = {
  sku: 'COLA-15-ORIGINAL',
  name: 'Coca-Cola original',
  brand: 'Coca-Cola',
  presentation: '1.5 L',
  price: 7200,
  stock: 12,
  category: 'Bebidas',
};
const chips = {
  sku: 'CHIPS-NATURAL-105',
  name: 'Papas Margarita natural',
  brand: 'Margarita',
  presentation: '105 g',
  price: 5200,
  stock: 12,
  category: 'Snacks',
};

store.mutate((state) => {
  state.productsByTenant[tenantId] = [structuredClone(cola), structuredClone(chips)];
  state.conversations.unshift({
    id: conversationId,
    tenantId,
    waId,
    messages: [],
    status: 'live',
    orderDraft: {
      delivery: true,
      items: [{
        lineId: 'line-gaseosa',
        rawName: 'gaseosa',
        catalogQuery: 'gaseosa',
        quantity: 2,
        selectionStatus: 'pending',
        catalogCandidates: [structuredClone(cola)],
      }, {
        lineId: 'line-papas',
        rawName: 'papas',
        catalogQuery: 'papas',
        quantity: 2,
        selectionStatus: 'pending',
        catalogCandidates: [structuredClone(chips)],
      }],
      missingFields: ['selection:line-gaseosa', 'selection:line-papas'],
    },
  });
});

try {
  await runtime.handleDeliveryOrder({
    tenantId,
    conversationId,
    normalized: { waId, text: 'Coca-Cola original de litro y medio', traceId: 'quantity-selection' },
    customerProfile: null,
    plan: {
      intent: 'order_clarification',
      order: {
        delivery: true,
        // This is the shape generated by the fallback interpreter: it
        // identifies the selected variant but supplies its conventional
        // default quantity because the selection text has no new amount.
        items: [{
          rawName: 'Coca-Cola original 1.5 L',
          catalogQuery: 'Coca-Cola original 1.5 L',
          quantity: 1,
        }],
      },
      missingFields: [],
    },
  });

  const draft = store.getState().conversations.find((item) => item.id === conversationId).orderDraft;
  assert.equal(draft.items.length, 2, 'The selection replaces its pending line and retains unrelated pending lines');
  const selectedCola = draft.items.find((item) => item.product?.sku === cola.sku);
  const pendingChips = draft.items.find((item) => item.lineId === 'line-papas');
  assert.ok(selectedCola);
  assert.equal(selectedCola.quantity, 2, 'A variant selection without an explicit quantity keeps the requested quantity');
  assert.equal(pendingChips.quantity, 2, 'Selecting one item does not lose the remaining pending item or its quantity');
  assert.equal(pendingChips.selectionStatus, 'pending');
  assert.equal(draft.subtotal, 14400);

  const explicitConversationId = 'quantity-reconciliation-explicit';
  store.mutate((state) => {
    state.conversations.unshift({
      id: explicitConversationId,
      tenantId,
      waId: '573000000902',
      messages: [],
      status: 'live',
      orderDraft: {
        delivery: true,
        items: [{
          lineId: 'line-gaseosa-explicit',
          rawName: 'gaseosa',
          catalogQuery: 'gaseosa',
          quantity: 2,
          selectionStatus: 'pending',
          catalogCandidates: [structuredClone(cola)],
        }],
        missingFields: ['selection:line-gaseosa-explicit'],
      },
    });
  });
  await runtime.handleDeliveryOrder({
    tenantId,
    conversationId: explicitConversationId,
    normalized: { waId: '573000000902', text: 'Mejor tres Coca-Cola original de litro y medio', traceId: 'quantity-explicit-change' },
    customerProfile: null,
    plan: {
      intent: 'order_clarification',
      order: { delivery: true, items: [{ rawName: 'Coca-Cola original 1.5 L', catalogQuery: 'Coca-Cola original 1.5 L', quantity: 3, quantityExplicit: true }] },
      missingFields: [],
    },
  });
  const explicitDraft = store.getState().conversations.find((item) => item.id === explicitConversationId).orderDraft;
  assert.equal(explicitDraft.items[0].quantity, 3, 'An explicitly changed quantity overrides the pending quantity');
  assert.equal(explicitDraft.subtotal, 21600);

  const amountConversationId = 'amount-reconciliation';
  const bananas = {
    sku: 'BAN-001',
    name: 'Banano por peso',
    brand: 'Granja',
    presentation: '1 kg',
    price: 1000,
    stock: 12,
    category: 'Frutas',
    allowsSaleByAmount: true,
  };
  store.mutate((state) => {
    state.productsByTenant[tenantId].push(structuredClone(bananas));
    state.conversations.unshift({
      id: amountConversationId,
      tenantId,
      waId: '573000000903',
      messages: [],
      status: 'live',
      orderDraft: {
        delivery: true,
        items: [{
          lineId: 'line-banano-amount',
          rawName: 'banano',
          catalogQuery: 'banano',
          quantity: null,
          budgetAmount: 5000,
          selectionStatus: 'pending',
          catalogCandidates: [structuredClone(bananas)],
        }],
        missingFields: ['selection:line-banano-amount'],
      },
    });
  });
  await runtime.handleDeliveryOrder({
    tenantId,
    conversationId: amountConversationId,
    normalized: { waId: '573000000903', text: 'Banano por peso', traceId: 'amount-selection' },
    customerProfile: null,
    plan: {
      intent: 'order_clarification',
      order: {
        delivery: true,
        // Selecting the catalog variant does not state a new amount. The
        // original amount must remain the commercial instruction.
        items: [{ rawName: 'Banano por peso', catalogQuery: 'Banano por peso', quantity: 1, quantityExplicit: false, budgetAmount: null }],
      },
      missingFields: [],
    },
  });
  const amountDraft = store.getState().conversations.find((item) => item.id === amountConversationId).orderDraft;
  assert.equal(amountDraft.items[0].quantity, null, 'A sale by amount is not converted into one unit during selection');
  assert.equal(amountDraft.items[0].budgetAmount, 5000, 'A variant selection preserves the amount explicitly requested earlier');
  assert.equal(amountDraft.items[0].lineTotal, 5000);
  assert.equal(amountDraft.subtotal, 5000);

  const initialAmountConversationId = 'amount-initial-request';
  store.mutate((state) => {
    state.conversations.unshift({
      id: initialAmountConversationId,
      tenantId,
      waId: '573000000904',
      messages: [],
      status: 'live',
      orderDraft: null,
    });
  });
  await runtime.handleDeliveryOrder({
    tenantId,
    conversationId: initialAmountConversationId,
    normalized: { waId: '573000000904', text: 'Dame cinco mil de banano', traceId: 'amount-initial-request' },
    customerProfile: null,
    plan: {
      intent: 'delivery_order',
      order: {
        delivery: true,
        items: [{ rawName: 'banano', catalogQuery: 'banano', quantity: 1, budgetAmount: 5000, budgetAmountExplicit: true }],
      },
      missingFields: [],
    },
  });
  const initialAmountDraft = store.getState().conversations.find((item) => item.id === initialAmountConversationId).orderDraft;
  assert.equal(initialAmountDraft.items[0].saleMode, 'amount');
  assert.equal(initialAmountDraft.items[0].quantity, null, 'An amount request never becomes a fallback unit');
  assert.equal(initialAmountDraft.items[0].requestedAmount, 5000);
  assert.equal(initialAmountDraft.items[0].lineTotal, 5000, 'The requested budget is the line total');
  assert.equal(initialAmountDraft.subtotal, 5000);

  const closedPackageAmountConversationId = 'amount-closed-package';
  store.mutate((state) => {
    state.conversations.unshift({
      id: closedPackageAmountConversationId,
      tenantId,
      waId: '573000000905',
      messages: [],
      status: 'live',
      orderDraft: null,
    });
  });
  await runtime.handleDeliveryOrder({
    tenantId,
    conversationId: closedPackageAmountConversationId,
    normalized: { waId: '573000000905', text: 'Dame cinco mil de Coca-Cola', traceId: 'amount-closed-package' },
    customerProfile: null,
    plan: {
      intent: 'delivery_order',
      order: {
        delivery: true,
        items: [{ rawName: 'Coca-Cola', catalogQuery: 'Coca-Cola', quantity: 1, budgetAmount: 5000, budgetAmountExplicit: true }],
      },
      missingFields: [],
    },
  });
  const closedPackageDraft = store.getState().conversations.find((item) => item.id === closedPackageAmountConversationId).orderDraft;
  assert.equal(closedPackageDraft.items[0].product, null, 'A closed package cannot be silently sold by amount');
  assert.equal(closedPackageDraft.items[0].quantity, null);
  assert.equal(closedPackageDraft.items[0].saleMode, 'amount');
  assert.ok(closedPackageDraft.missingFields.some((field) => field.startsWith('commercial_review:')));

  const weightConversationId = 'weight-initial-request';
  const quesoAlCorte = {
    sku: 'QUESO-CORTE-001',
    name: 'Queso doble crema al corte',
    brand: 'Lácteos del barrio',
    presentation: 'Al corte',
    price: 43200,
    stock: 1,
    category: 'Charcutería',
    attributes: { commerce: { saleModes: ['weight'], weight: {
      pricePerKg: 43200, stockGrams: 12000, minGrams: 50, incrementGrams: 50,
    } } },
  };
  const quesoEmpacado = {
    sku: 'QUESO-PAQ-250', name: 'Queso doble crema empacado', presentation: '250 g', price: 10800, stock: 24,
    category: 'Lácteos', attributes: { measure: { amount: 250, unit: 'g', dimension: 'weight' } },
  };
  store.mutate((state) => {
    state.productsByTenant[tenantId].push(structuredClone(quesoAlCorte), structuredClone(quesoEmpacado));
    state.conversations.unshift({ id: weightConversationId, tenantId, waId: '573000000906', messages: [], status: 'live', orderDraft: null });
  });
  await runtime.handleDeliveryOrder({
    tenantId,
    conversationId: weightConversationId,
    normalized: { waId: '573000000906', text: 'Media libra de queso doble crema', traceId: 'weight-initial-request' },
    customerProfile: null,
    plan: {
      intent: 'delivery_order',
      order: { delivery: true, items: [{
        rawName: 'queso doble crema', catalogQuery: 'queso doble crema',
        requestedMeasure: 'media libra', requestedWeight: { amount: 0.5, unit: 'lb' },
      }] },
      missingFields: [],
    },
  });
  const weightDraft = store.getState().conversations.find((item) => item.id === weightConversationId).orderDraft;
  assert.equal(weightDraft.items[0].product?.sku, quesoAlCorte.sku, 'A weight request uses only catalog references explicitly configured for weight sale');
  assert.equal(weightDraft.items[0].saleMode, 'weight');
  assert.equal(weightDraft.items[0].requestedWeightGrams, 250);
  assert.equal(weightDraft.items[0].unitPricePerKg, 43200);
  assert.equal(weightDraft.items[0].lineTotal, 10800);
  assert.equal(weightDraft.subtotal, 10800);
  assert.ok(!weightDraft.missingFields.some((field) => field.startsWith('quantity:')), 'A validated weight replaces the unit quantity requirement');

  console.log('Order quantity reconciliation passed.');
} finally {
  runtime.stop();
  integrationOutbox.stop();
  await store.close?.();
  fs.rmSync(dir, { recursive: true, force: true });
}
